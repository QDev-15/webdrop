/* Giỏ hàng đơn giản (localStorage) */
function getCart() {
  try { return JSON.parse(localStorage.getItem('dg_cart') || '[]'); } catch { return []; }
}
function saveCart(cart) {
  localStorage.setItem('dg_cart', JSON.stringify(cart));
  updateCartCount();
}
function addToCart(productId) {
  const cart = getCart();
  const idx = cart.findIndex(i => i.id === productId);
  if (idx >= 0) cart[idx].qty++;
  else cart.push({ id: productId, qty: 1 });
  saveCart(cart);
}
function updateCartCount() {
  const cart = getCart();
  const total = cart.reduce((s, i) => s + i.qty, 0);
  document.querySelectorAll('.dg-cart-count').forEach(el => {
    el.textContent = total;
    el.hidden = total === 0;
  });
}

/* Event delegation cho nút thêm giỏ hàng */
document.addEventListener('click', function(e) {
  const btn = e.target.closest('.dg-btn--cart[data-id]');
  if (!btn) return;
  const id = parseInt(btn.dataset.id, 10);
  if (!id) return;
  addToCart(id);
  btn.classList.add('dg-btn--added');
  setTimeout(() => btn.classList.remove('dg-btn--added'), 1200);
});

/* Khởi tạo số đếm giỏ hàng khi tải trang */
document.addEventListener('DOMContentLoaded', updateCartCount);
